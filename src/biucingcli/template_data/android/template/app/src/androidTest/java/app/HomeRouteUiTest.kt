package {{PACKAGE_NAME}}

import androidx.compose.ui.test.assertIsDisplayed
import androidx.compose.ui.test.junit4.createAndroidComposeRule
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class HomeRouteUiTest {
    @get:Rule
    val composeRule = createAndroidComposeRule<MainActivity>()

    @Test
    fun homeScreenShowsGeneratedGreeting() {
        composeRule.onNodeWithText("{{DISPLAY_NAME_KOTLIN}}", substring = true).assertIsDisplayed()
        composeRule.onNodeWithText("Generated by BiucingCLI", substring = true).assertIsDisplayed()
        composeRule.onNodeWithText("计算示例").performClick()
        composeRule.waitUntil(10_000) {
            composeRule
                .onAllNodes(
                    androidx.compose.ui.test
                        .hasText("42"),
                ).fetchSemanticsNodes()
                .isNotEmpty()
        }
        composeRule.onNodeWithText("42").assertIsDisplayed()
        composeRule.activityRule.scenario.recreate()
        composeRule.onNodeWithText("42").assertIsDisplayed()
        composeRule.onNodeWithText("设置").performClick()
        composeRule.onNodeWithText("Release channel: beta", substring = true).assertIsDisplayed()
    }
}
